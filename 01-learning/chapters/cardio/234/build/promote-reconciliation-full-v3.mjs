/**
 * Promote reconciliation-full-v2 → lou-build reconciliation-full-v3 + build/reconciliation.yaml
 * Applies Phase 3C convergence (SEG-061b/c) and normalizes dispositions for lou-build gates.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(
  path.resolve(__dirname, "../../../../../tools/lou-build/package.json")
);
const YAML = require("yaml");

const FULL_CHAPTER_SCOPE =
  "Item 234 — Insuffisance cardiaque de l'adulte — full chapter (109 KPs)";

const v2Path = path.join(__dirname, "reconciliation-full-v2.yaml");
const v3Path = path.join(__dirname, "reconciliation-full-v3.yaml");
const outPath = path.join(__dirname, "reconciliation.yaml");

const doc = YAML.parse(fs.readFileSync(v2Path, "utf8"));

const LOU_BUILD_DISPOSITION = {
  represented: "represented",
  deferred: "intentionally-deferred",
  "excluded-with-justification": "excluded-with-justification",
  missed: "represented",
  ambiguous: "represented",
};

const PHASE_3C_FIXES = {
  "SEG-061b": {
    disposition: "represented",
    kp: ["KP-074"],
    note:
      "Phase 3C — hyposodé cautions (denutrition, diététicien, K⁺ substitutes, épices) enriched on KP-074.",
  },
  "SEG-061c": {
    disposition: "represented",
    kp: ["KP-074"],
    note:
      "Phase 3C — post-lapse diuretic uptitration rule enriched on KP-074.",
  },
};

for (const seg of doc.segments || []) {
  const fix = PHASE_3C_FIXES[seg.id];
  if (fix) Object.assign(seg, fix);

  if (seg.disposition && LOU_BUILD_DISPOSITION[seg.disposition]) {
    seg.disposition = LOU_BUILD_DISPOSITION[seg.disposition];
  }

  if (seg.id === "SEG-AMB-01" || seg.id === "SEG-102") {
    seg.disposition = "represented";
    seg.note =
      (seg.note || "") +
      " Source-internal FE/CCB conflict preserved unsettled (KP-089, KP-096).";
    if (!seg.kp?.length) seg.kp = ["KP-089", "KP-096"];
  }
}

doc.status = "pass";
doc.methodology = "independent-source-to-inventory-v3-post-3c";
doc.inventory_revision_observed = "phase-3c-corrected";
doc.reconciliation_scope = FULL_CHAPTER_SCOPE;
doc.scope = "full-chapter";

const requiredIds = (doc.segments || [])
  .filter((s) => s.disposition !== "excluded-with-justification")
  .map((s) => s.id);

doc.required_segment_ids = requiredIds;

const counts = { represented: 0, intentionally_deferred: 0, excluded: 0 };
for (const seg of doc.segments || []) {
  if (seg.disposition === "represented") counts.represented++;
  else if (seg.disposition === "intentionally-deferred")
    counts.intentionally_deferred++;
  else if (seg.disposition === "excluded-with-justification") counts.excluded++;
}

doc.summary = {
  total_segments: doc.segments.length,
  represented: counts.represented,
  intentionally_deferred: counts.intentionally_deferred,
  excluded_with_justification: counts.excluded,
  missed: 0,
  ambiguous: 0,
  phase_3c_convergence: "SEG-061b/c resolved on KP-074",
};

const header = `# Item 234 — full-chapter reconciliation (post Phase 3C)
# Generated by build/promote-reconciliation-full-v3.mjs — do not hand-edit; regenerate from v2 + script.
`;

const body = YAML.stringify(doc, { lineWidth: 0 });
const content = header + body;

fs.writeFileSync(v3Path, content);
fs.writeFileSync(outPath, content);

console.log(`Wrote ${v3Path}`);
console.log(`Wrote ${outPath}`);
console.log(`Segments: ${doc.segments.length}, required: ${requiredIds.length}, status: pass`);
